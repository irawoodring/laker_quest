# Area to include (degrees) and tile size (meters).
NORTH, SOUTH = 42.9745, 42.9500
WEST, EAST = -85.9135, -85.8735
TILE_M = 9.0
SUPER = 4   # supersampling for polygon coverage
STAND_DEPTH = 3   # tiles of bleachers along each side of a stadium field

LAT0 = (NORTH + SOUTH) / 2
M_PER_DEG_LAT = 111_132.0
M_PER_DEG_LON = 111_320.0 * math.cos(math.radians(LAT0))
W = int(round((EAST - WEST) * M_PER_DEG_LON / TILE_M))
H = int(round((NORTH - SOUTH) * M_PER_DEG_LAT / TILE_M))

