"""Build Laker Quest's campus tile map from OpenStreetMap data.

Usage:
    python3 tools/osm_to_map.py <map.osm> [--campus-image allendale_campus_map.jpg] [--preview out.png]

<map.osm> is an OpenStreetMap XML export (openstreetmap.org -> Export) that
covers the Allendale campus. Buildings, roads, footpaths, parking, water,
woods, fields and the golf course are drawn into tiles of TILE_M meters and
written to src/campus_map.js, one row per line.

--campus-image is GVSU's campus map image (the A-F / 1-9 grid version). When
given, parking lots get their permit colors from it, and the converter fits
the transform from that image's pixels to tiles, so signs, NPCs and enemy
areas written in image coordinates (campus.js, data.js) land in the right
places.
"""
