LQ.FONT_HEIGHT = 9;   // rows including descenders
LQ.LINE_HEIGHT = 12;  // pixels between text lines

// Pre-render every glyph into a small canvas per color so text drawing is a
// handful of drawImage calls.
LQ.fontCache = {};

LQ.glyphWidth = function (ch) {
  const g = LQ.FONT_GLYPHS[ch] || LQ.FONT_GLYPHS['?'];
  return g[0].length + 1;
};

LQ.textWidth = function (str) {
  let w = 0;
  for (const ch of str) w += LQ.glyphWidth(ch);
  return Math.max(0, w - 1);
};

LQ.getGlyphCanvas = function (ch, color) {
  const key = ch + '|' + color;
  if (LQ.fontCache[key]) return LQ.fontCache[key];
  const g = LQ.FONT_GLYPHS[ch] || LQ.FONT_GLYPHS['?'];
  const c = document.createElement('canvas');
  c.width = g[0].length;
  c.height = LQ.FONT_HEIGHT;
  const cx = c.getContext('2d');
  cx.fillStyle = color;
  g.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') cx.fillRect(x, y, 1, 1);
  });
  LQ.fontCache[key] = c;
  return c;
};

LQ.drawText = function (ctx, str, x, y, color, shadow) {
  color = color || '#ffffff';
  let cx = x;
  for (const ch of str) {
    if (shadow) ctx.drawImage(LQ.getGlyphCanvas(ch, shadow), cx + 1, y + 1);
    ctx.drawImage(LQ.getGlyphCanvas(ch, color), cx, y);
    cx += LQ.glyphWidth(ch);
  }
  return cx;
};

// Word-wrap a string to fit maxWidth pixels. '\n' forces a break.
LQ.wrapText = function (str, maxWidth) {
  const lines = [];
  for (const para of str.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const trial = line ? line + ' ' + word : word;
      if (LQ.textWidth(trial) > maxWidth && line) {
        lines.push(line);
        line = word;
      } else {
        line = trial;
      }
    }
    lines.push(line);
  }
  return lines;
};
